import {test} from 'node:test';import assert from 'node:assert/strict';import {parseCSV,cleanRows,toCSV}from './core.mjs';
test('basic CSV',()=>assert.deepEqual(parseCSV('a,b\n1,2\n'),[['a','b'],['1','2']]));
test('BOM and CRLF',()=>assert.deepEqual(parseCSV('\uFEFFa,b\r\n1,2'),[['a','b'],['1','2']]));
test('quoted comma',()=>assert.equal(parseCSV('a\n"b,c"')[1][0],'b,c'));
test('quoted newline',()=>assert.equal(parseCSV('a\n"b\nc"')[1][0],'b\nc'));
test('escaped quotes',()=>assert.equal(parseCSV('a\n"b""c"')[1][0],'b"c'));
test('trailing empty cell',()=>assert.deepEqual(parseCSV('a,b\n1,'),[['a','b'],['1','']]));
test('empty quoted final',()=>assert.deepEqual(parseCSV('a\n""'),[['a'],['']]));
test('unclosed quote rejected',()=>assert.throws(()=>parseCSV('a\n"bad')));
test('quote inside plain cell rejected',()=>assert.throws(()=>parseCSV('a\nb"c')));
test('trailing junk rejected',()=>assert.throws(()=>parseCSV('a\n"b"x')));
test('semicolon delimiter',()=>assert.deepEqual(parseCSV('a;b\n1;2',';'),[['a','b'],['1','2']]));
test('tab delimiter',()=>assert.deepEqual(parseCSV('a\tb\n1\t2','\t'),[['a','b'],['1','2']]));
test('trim, dedupe, empty report',()=>{let r=cleanRows(parseCSV('id,name\n001, Alice \n001,Alice\n,\n002,Bob\n'));assert.deepEqual(r.rows,[['id','name'],['001','Alice'],['002','Bob']]);assert.deepEqual(r.report,{input:4,kept:2,duplicates:1,empty:1,changed:1});});
test('leading zeros preserved',()=>assert.equal(cleanRows(parseCSV('id\n00001')).rows[1][0],'00001'));
test('uneven row rejected',()=>assert.throws(()=>cleanRows(parseCSV('a,b\n1,2,3'))));
test('empty header rejected',()=>assert.throws(()=>cleanRows(parseCSV(',\n1,2'))));
test('empty input rejected',()=>assert.throws(()=>cleanRows(parseCSV(''))));
test('dedupe can be disabled',()=>assert.equal(cleanRows(parseCSV('a\n1\n1'),{dedupe:false}).report.kept,2));
test('formula protection',()=>{let r=toCSV([['x'],['=1+1'],[' +cmd'],['-42'],['@SUM(A1)']]);assert.equal(r.protectedCells,4);assert.ok(r.text.includes("'=1+1"));});
test('formula raw explicit opt-out',()=>assert.equal(toCSV([['=1']],{protect:false}).protectedCells,0));
test('round trip quote/newline unicode',()=>{let rows=[['a','b'],['한글','x,"y"\nz'],['001','💡']];assert.deepEqual(parseCSV(toCSV(rows).text),rows);});
test('row ceiling',()=>assert.throws(()=>parseCSV('a\n'+'1\n'.repeat(20001))));
